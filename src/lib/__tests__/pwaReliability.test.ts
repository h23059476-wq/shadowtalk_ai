/**
 * Batch 5 — PWA manifest, asset and installation reliability.
 *
 * Source-contract tests pinning the reliability fixes:
 *  1. index.html no longer references assets that do not exist (splash PNGs,
 *     safari-pinned-tab.svg) — every one of these produced a 404 on load.
 *  2. The manifest theme_color matches index.html's <meta name="theme-color">.
 *  3. The manifest has a stable `id`, maskable icon purposes, and no
 *     references to the missing masked-icon.svg.
 *  4. DownloadPage never dispatches a synthetic beforeinstallprompt event
 *     (a fake Event has no prompt(); it could never trigger the real
 *     browser install prompt and only polluted Navigation's state).
 *  5. Navigation removes BOTH its install-related listeners on unmount.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const read = (rel: string) => readFileSync(resolve(process.cwd(), rel), "utf8");

describe("PWA asset reliability", () => {
  it("index.html does not reference missing splash screen PNGs", () => {
    const html = read("index.html");
    expect(html).not.toContain("splash-640x1136.png");
    expect(html).not.toContain("splash-750x1334.png");
    expect(html).not.toContain("splash-1242x2208.png");
    expect(html).not.toContain("splash-1125x2436.png");
    expect(html).not.toContain("apple-touch-startup-image");
  });

  it("index.html does not link the missing safari-pinned-tab.svg", () => {
    const html = read("index.html");
    // Check actual link references, not comment mentions.
    expect(html).not.toMatch(/<link[^>]+safari-pinned-tab\.svg/);
  });

  it("every static icon referenced by index.html exists in public/", () => {
    const html = read("index.html");
    const hrefs = [...html.matchAll(/<link[^>]+href="(\/[^"']+\.(?:png|ico|svg))"/g)]
      .map((m) => m[1]);
    expect(hrefs.length).toBeGreaterThan(0);
    for (const href of hrefs) {
      const file = resolve(process.cwd(), "public", href.replace(/^\//, ""));
      expect(() => readFileSync(file), `missing asset: ${href}`).not.toThrow();
    }
    // The manifest itself is build-generated by vite-plugin-pwa (not a public/
    // file) — verify the link tag is present and points at the generated path.
    expect(html).toMatch(/<link[^>]+rel="manifest"[^>]+href="\/manifest.webmanifest"/);
  });

  it("vite.config includeAssets no longer lists the missing masked-icon.svg", () => {
    const cfg = read("vite.config.ts");
    // Parse the actual includeAssets array (comment mentions are irrelevant).
    const includeMatch = cfg.match(/includeAssets:\s*\[([^\]]*)\]/);
    expect(includeMatch).not.toBeNull();
    const names = (includeMatch![1].match(/'([^']+)'/g) || []).map((s) => s.replace(/'/g, ""));
    expect(names).not.toContain("masked-icon.svg");
  });

  it("every icon listed in includeAssets exists in public/", () => {
    const cfg = read("vite.config.ts");
    const includeMatch = cfg.match(/includeAssets:\s*\[([^\]]*)\]/);
    expect(includeMatch).not.toBeNull();
    const names = (includeMatch![1].match(/'([^']+)'/g) || []).map((s) => s.replace(/'/g, ""));
    for (const name of names) {
      const file = resolve(process.cwd(), "public", name);
      expect(() => readFileSync(file), `includeAssets entry missing: ${name}`).not.toThrow();
    }
  });
});

describe("PWA manifest correctness", () => {
  it("manifest theme_color matches index.html's theme-color meta", () => {
    const html = read("index.html");
    const meta = html.match(/<meta\s+name="theme-color"\s+content="([^"]+)"/);
    expect(meta).not.toBeNull();
    const cfg = read("vite.config.ts");
    const theme = cfg.match(/theme_color:\s*'([^']+)'/);
    expect(theme).not.toBeNull();
    // Case-insensitive compare (hex colors).
    expect(theme![1].toLowerCase()).toBe(meta![1].toLowerCase());
  });

  it("manifest declares a stable install id", () => {
    const cfg = read("vite.config.ts");
    expect(cfg).toMatch(/id:\s*'\//);
  });

  it("manifest icons declare maskable purpose", () => {
    const cfg = read("vite.config.ts");
    const iconBlock = cfg.slice(cfg.indexOf("icons: ["), cfg.indexOf("workbox:"));
    const purposes = iconBlock.match(/purpose:/g) || [];
    expect(purposes.length).toBeGreaterThanOrEqual(2);
    expect(iconBlock).toContain("'any maskable'");
  });

  it("manifest icon files exist in public/", () => {
    const cfg = read("vite.config.ts");
    const iconBlock = cfg.slice(cfg.indexOf("icons: ["), cfg.indexOf("workbox:"));
    const srcs = (iconBlock.match(/src:\s*'([^']+)'/g) || [])
      .map((s) => s.replace(/src:\s*'/, "").replace(/'/, ""));
    expect(srcs.length).toBeGreaterThanOrEqual(2);
    for (const src of srcs) {
      const file = resolve(process.cwd(), "public", src);
      expect(() => readFileSync(file), `manifest icon missing: ${src}`).not.toThrow();
    }
  });

  it("registerSW keeps the service worker registered (PWA/offline intact)", () => {
    const src = read("src/main.tsx");
    expect(src).toContain("registerSW({ immediate: true })");
    expect(src).not.toMatch(/registration\.unregister\s*\(/);
  });
});

describe("PWA installation reliability", () => {
  it("DownloadPage never dispatches a synthetic beforeinstallprompt event", () => {
    const src = read("src/pages/DownloadPage.tsx");
    expect(src).not.toMatch(/new Event\(\s*["']beforeinstallprompt["']\s*\)/);
    expect(src).not.toMatch(/dispatchEvent\([^)]*beforeinstallprompt/);
    // Honest standalone detection remains.
    expect(src).toContain("display-mode: standalone");
  });

  it("Navigation removes both install listeners on unmount (no leak)", () => {
    const src = read("src/components/Navigation.tsx");
    expect(src).toContain("window.removeEventListener('beforeinstallprompt', handler)");
    expect(src).toContain("window.removeEventListener('appinstalled', onInstalled)");
    // The appinstalled handler must be named (not an anonymous inline arrow).
    expect(src).toMatch(/const onInstalled = \(\) => setIsInstalled\(true\);/);
  });
});
